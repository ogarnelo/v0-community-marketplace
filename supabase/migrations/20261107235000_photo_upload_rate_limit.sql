-- Request quota for server-optimized photo uploads.
-- Only the authenticated server may reserve slots; the browser has no
-- direct read/insert/execute rights. Claims cover accepted upload attempts.
-- Do not use a SELECT + INSERT counter from the API: it is race-prone.
CREATE TABLE IF NOT EXISTS public.photo_upload_claims (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  claimed_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS photo_upload_claims_user_time_idx
  ON public.photo_upload_claims (user_id, claimed_at DESC);
ALTER TABLE public.photo_upload_claims ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.photo_upload_claims FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT ON public.photo_upload_claims TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.photo_upload_claims_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.claim_photo_upload_slot(p_user_id uuid)
RETURNS boolean
LANGUAGE plpgsql SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  now_at timestamptz := clock_timestamp();
  recent_10_minutes integer;
  recent_24_hours integer;
BEGIN
  IF p_user_id IS NULL THEN RETURN false; END IF;

  -- Per-user transaction lock ensures simultaneous uploads cannot bypass
  -- the combined short-window + daily caps.
  PERFORM pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(p_user_id::text, 91827)
  );
  SELECT count(*) FILTER (WHERE claimed_at >= now_at - interval '10 minutes'),
         count(*)
  INTO recent_10_minutes, recent_24_hours
  FROM public.photo_upload_claims
  WHERE user_id = p_user_id
    AND claimed_at >= now_at - interval '24 hours';

  IF recent_10_minutes >= 12 OR recent_24_hours >= 60 THEN
    RETURN false;
  END IF;

  INSERT INTO public.photo_upload_claims (user_id, claimed_at)
  VALUES (p_user_id, now_at);
  RETURN true;
END;
$$;
REVOKE ALL ON FUNCTION public.claim_photo_upload_slot(uuid)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.claim_photo_upload_slot(uuid)
  TO service_role;
